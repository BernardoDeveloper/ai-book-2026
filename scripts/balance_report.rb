#!/usr/bin/env ruby
# frozen_string_literal: true

# Balance report for structural editing: how much of the book each unit and
# each source post takes, and how much of a unit repeats text found elsewhere.
# Changes nothing; writes build/<lang>/balance.md.
#
#   units     words, share of the narrative, posts cited, figures, and the
#             words in 8+-word runs shared with other units ("overlap")
#   posts     words the book spends on each post (sum of its src-marked
#             paragraphs), most expensive first
#
# Usage: scripts/balance_report.rb [--lang pt]

require "optparse"
require "yaml"
require "fileutils"
require "set"

opts = { lang: "pt" }
OptionParser.new { |o| o.on("--lang LANG") { opts[:lang] = _1 } }.parse!
ROOT = File.expand_path("..", __dir__)
LANG = opts[:lang]
RUN = 8

outline = YAML.load_file(File.join(ROOT, "book", "outline.yml"))
order = outline["front"].map { _1["id"] } +
        outline["parts"].flat_map { |p| p["chapters"] ? p["chapters"].map { _1["id"] } : [p["id"]] } +
        outline["back"].reject { _1["kind"] == "generated" }.map { _1["id"] }
file_of = ->(id) { File.join(ROOT, "book", LANG, id == "prefacio" ? "index.md" : "#{id}.md") }
order.select! { File.exist?(file_of.(_1)) }

words_in = ->(t) { t.gsub(/<!--.*?-->/m, "").gsub(/\[([^\]]*)\]\{[^}]*\}/, '\1').gsub(/\[@[^\]]*\]|@(?:sec|fig|tbl)-[\w-]+/, "").scan(/[\p{L}\d][\p{L}\d'-]*/) }

units = order.to_h do |id|
  body = File.read(file_of.(id)).sub(/\A---.*?^---[ \t]*$/m, "")
  # paragraphs attributed to the src marker above them
  per_post = Hash.new(0)
  current = nil
  body.split(/\n{2,}/).each do |para|
    if (m = para.match(/<!-- src: ([^ ]+) -->/))
      current = m[1]
    end
    next if para.lstrip.start_with?("#", "!", ":::")

    per_post[current || "(none)"] += words_in.(para).size
  end
  prose = body.lines.reject { _1.lstrip.start_with?("!", "|", "#", ":::") }.join
  [id, { words: words_in.(prose).map(&:downcase), per_post: per_post, figs: body.scan(/\{#fig-/).size }]
end

grams = Hash.new { |h, k| h[k] = Set.new }
units.each { |id, u| u[:words].each_cons(RUN) { grams[_1.join(" ")] << id } }
units.each_value do |u|
  shared = Set.new
  u[:words].each_cons(RUN).with_index { |g, i| (i...(i + RUN)).each { shared << _1 } if grams[g.join(" ")].size > 1 }
  u[:overlap] = shared.size
end

narrative = order.reject { _1.start_with?("ap") }
total = narrative.sum { units[_1][:words].size }.to_f
out = ["# Balance report (#{LANG})", "", "Generated by scripts/balance_report.rb. Narrative = preface to afterword (appendices listed separately).", "",
       "## Units", "", "| unit | words | % narrative | posts | figures | overlap words |", "|---|---:|---:|---:|---:|---:|"]
order.each do |id|
  u = units[id]
  posts = u[:per_post].keys.count { _1.start_with?("2026/") }
  pct = id.start_with?("ap") ? "" : format("%.1f", 100 * u[:words].size / total)
  out << "| #{id} | #{u[:words].size} | #{pct} | #{posts} | #{u[:figs]} | #{u[:overlap]} |"
end
out << "" << "Narrative total: #{total.to_i} words." << ""

post_words = Hash.new { |h, k| h[k] = Hash.new(0) }
units.each { |id, u| u[:per_post].each { |p, w| post_words[p][id] += w if p.start_with?("2026/") } }
out << "## Posts by words spent" << "" << "| post | words | units |" << "|---|---:|---|"
post_words.sort_by { -_2.values.sum }.each do |p, by|
  out << "| #{p.delete_prefix('2026/')} | #{by.values.sum} | #{by.sort_by { -_2 }.map { |u, w| "#{u} #{w}" }.join(', ')} |"
end

dir = File.join(ROOT, "build", LANG)
FileUtils.mkdir_p(dir)
File.write(File.join(dir, "balance.md"), out.join("\n") + "\n")
puts "balance report (#{LANG}): #{order.size} units, #{post_words.size} posts -> build/#{LANG}/balance.md"
