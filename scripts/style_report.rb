#!/usr/bin/env ruby
# frozen_string_literal: true

# Copyedit step 1 (docs/COPYEDIT.md): a mechanical style report for a book
# written by many hands. Changes nothing; writes build/<lang>/style-report.md.
#
#   repetition   7+-word sequences shared by different units (reused
#                sentences, retold anecdotes)
#   phrases      4-6-word phrases recurring in many units (callbacks or tics)
#   overuse      words a unit uses far more than the rest of the book
#   variants     the same term spelled differently (case, hyphen, space)
#   agreement    PT: "do que" followed by a conjugated verb (WRITER.md wants
#                an infinitive on both sides of a comparison)
#
# Usage: scripts/style_report.rb [--lang pt] [--min-run 7]

require "optparse"
require "fileutils"
require "set"

opts = { lang: "pt", min_run: 7 }
OptionParser.new do |o|
  o.on("--lang LANG") { opts[:lang] = _1 }
  o.on("--min-run N", Integer) { opts[:min_run] = _1 }
end.parse!

ROOT = File.expand_path("..", __dir__)
LANG = opts[:lang]
GENERATED = %w[glossario bibliografia fontes creditos].freeze

# Reader-visible prose only: no front matter, comments, code, figures,
# markup, citations or cross-references.
def prose(text)
  text = text.sub(/\A---.*?^---[ \t]*$/m, "")
  text = text.gsub(/<!--.*?-->/m, "").gsub(/^```.*?^```/m, "")
  text = text.lines.reject { _1.lstrip.start_with?("!", "|", ":::", "#") }.join
  text.gsub(/\[([^\]]*)\]\{[^}]*\}/) { Regexp.last_match(1) }
      .gsub(/\[@[^\]]*\]|@(?:sec|fig|tbl)-[\w-]+|\{#[^}]*\}/, "")
      .gsub(/[*_`>]/, "")
end

units = Dir[File.join(ROOT, "book", LANG, "*.md")].sort
         .reject { GENERATED.include?(File.basename(_1, ".md")) }
         .to_h { |f| [File.basename(f, ".md") == "index" ? "prefacio" : File.basename(f, ".md"), prose(File.read(f))] }
words_of = ->(t) { t.downcase.scan(/[\p{L}\d][\p{L}\d'-]*/) }
tokens = units.transform_values { words_of.(_1) }
out = ["# Style report (#{LANG})", "", "Generated by scripts/style_report.rb. A worklist, not a verdict: " \
       "deliberate callbacks and quotations will show up too.", ""]

# --- repetition across units ---------------------------------------------------
# Mark every position whose n-word window also occurs in another unit, merge
# consecutive marks into maximal spans, and report each repeated passage once
# with the units that contain it.
n = opts[:min_run]
seen = Hash.new { |h, k| h[k] = [] }
tokens.each do |id, ws|
  ws.each_cons(n).with_index { |gram, i| seen[gram.join(" ")] << id }
end
joined = tokens.transform_values { " #{_1.join(' ')} " }
passages = {}
tokens.each do |id, ws|
  marks = (0..ws.size - n).select { |i| seen[ws[i, n].join(" ")].uniq.size > 1 }
  marks.slice_when { |a, b| b != a + 1 }.each do |run|
    text = ws[run.first..(run.last + n - 1)].join(" ")
    next if passages.key?(text) || passages.keys.any? { _1.include?(text) }

    passages.delete_if { |k, _| text.include?(k) }
    passages[text] = joined.select { |_, j| j.include?(" #{ws[run.first, n].join(' ')} ") }.keys
  end
end
out << "## Repetition across units (passages of #{n}+ words found in more than one unit)" << ""
if passages.empty?
  out << "None." << ""
else
  passages.sort_by { |k, us| [-k.split.size, -us.size] }.first(80).each do |k, us|
    out << "- (#{k.split.size} words) \"#{k.size > 240 ? "#{k[0, 240]}…" : k}\": #{us.join(', ')}"
  end
  out << "" << "(#{passages.size} passages#{passages.size > 80 ? ', longest 80 shown' : ''})" << ""
end
runs = passages.keys

# --- recurring phrases (callbacks or tics) ------------------------------------
STOPW = %w[de da do das dos a o as os e é que em no na nos nas um uma pra para com por se não mais
           the a an of to and in is it that for on with as was be this you i].freeze
phrase_units = Hash.new { |h, k| h[k] = Set.new }
tokens.each do |id, ws|
  (4..6).each do |len|
    ws.each_cons(len) do |g|
      next if STOPW.include?(g.first) || STOPW.include?(g.last)

      phrase_units[g.join(" ")] << id
    end
  end
end
recurring = phrase_units.select { |_, us| us.size >= 4 }
recurring = recurring.reject { |k, _| recurring.any? { |o, _| o != k && o.include?(k) && recurring[o].size >= recurring[k].size } }
out << "## Recurring phrases (in 4+ units)" << ""
recurring.sort_by { |k, us| [-us.size, k] }.first(60).each { |k, us| out << "- \"#{k}\" (#{us.size}): #{us.to_a.join(', ')}" }
out << "" if recurring.any?
out << "None." << "" if recurring.empty?

# --- overused words per unit -----------------------------------------------------
total = Hash.new(0)
tokens.each_value { |ws| ws.each { total[_1] += 1 } }
all_words = total.values.sum.to_f
out << "## Overused words (a unit uses a word 6x+ its book-wide rate, at least 6 times)" << ""
hits = []
tokens.each do |id, ws|
  local = ws.tally
  local.each do |w, c|
    next if c < 6 || w.size < 5 || STOPW.include?(w)

    rate_unit = c / ws.size.to_f
    rate_book = (total[w] - c) / [(all_words - ws.size), 1].max
    hits << [id, w, c, rate_book.zero? ? Float::INFINITY : rate_unit / rate_book] if rate_book.zero? || rate_unit / rate_book >= 6
  end
end
hits.sort_by { -_1[3] }.first(60).each { |id, w, c, r| out << "- #{id}: \"#{w}\" ×#{c} (#{r.infinite? ? 'only here' : "#{r.round}× book rate"})" }
out << "" << "(proper nouns and chapter topics will appear here legitimately)" << ""

# --- terminology variants -------------------------------------------------------
norm = ->(s) { s.downcase.delete(" -") }
forms = Hash.new { |h, k| h[k] = Hash.new(0) }
units.each_value do |t|
  t.scan(/\b[\p{L}\d][\p{L}\d]*(?:[ -][\p{L}\d]+)?\b/).each do |f|
    next if f.size < 4

    forms[norm.(f)][f] += 1
  end
end
variants = forms.select do |_, fs|
  fs.size > 1 && fs.keys.map(&:downcase).uniq.size > 1 && fs.values.sum >= 3 &&
    fs.keys.all? { _1.match?(/\A[\p{L}\d]/) } && fs.keys.any? { _1.include?("-") || _1.match?(/\p{Lu}.*\p{Lu}/) }
end
out << "## Terminology variants (same term, different spelling)" << ""
variants.sort.first(60).each { |_, fs| out << "- " + fs.sort_by { -_2 }.map { |f, c| "\"#{f}\" ×#{c}" }.join(", ") }
out << "None." if variants.empty?
out << ""

# --- PT comparatives ---------------------------------------------------------------
if LANG == "pt"
  out << "## \"do que\" + conjugated verb (WRITER.md: infinitive on both sides)" << ""
  found = []
  units.each do |id, t|
    t.scan(/[^.!?\n]*\bdo que (?:\p{L}+ )?(\p{L}+(?:ou|eu|aram|eram|iram|ava|ia|ou))\b[^.!?\n]*[.!?]?/) do
      found << "- #{id}: #{Regexp.last_match(0).strip[0, 160]}"
    end
  end
  out.concat(found.empty? ? ["None."] : found.first(40)) << ""
end

dir = File.join(ROOT, "build", LANG)
FileUtils.mkdir_p(dir)
File.write(File.join(dir, "style-report.md"), out.join("\n"))
puts "style report (#{LANG}): #{runs.size} repeated runs, #{recurring.size} recurring phrases, " \
     "#{hits.size} overuse hits, #{variants.size} term variants -> build/#{LANG}/style-report.md"
